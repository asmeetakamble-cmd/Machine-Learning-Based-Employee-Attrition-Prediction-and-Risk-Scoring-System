#EDA Job Role

role_attrition = (
    data.groupby("JobRole")["Attrition"]
    .agg(["count","sum","mean"])
    .sort_values("mean", ascending=False)
)
role_attrition["AttritionRate"] = role_attrition["mean"] * 100

print(role_attrition)

